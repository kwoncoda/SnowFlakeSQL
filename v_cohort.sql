CREATE OR REPLACE VIEW V_COHORT AS

WITH COHORTS AS (

    SELECT 2021 AS COHORT_YEAR, TO_DATE('2021-01-01') AS T
    UNION ALL
    SELECT 2022, TO_DATE('2022-01-01')
    UNION ALL
    SELECT 2023, TO_DATE('2023-01-01')
    UNION ALL
    SELECT 2024, TO_DATE('2024-01-01')

),

BASE AS (

    SELECT
        F.*,
        TRY_TO_DATE(F.LICENSE_DATE) AS LICENSE_DT,
        TRY_TO_DATE(F.CLOSE_DATE) AS CLOSE_DT

    FROM FOOD_ALL F

)

SELECT
    B.*,

    C.COHORT_YEAR,
    C.T AS COHORT_DATE,

    CASE
        WHEN B.CLOSE_DT > C.T
         AND B.CLOSE_DT <= DATEADD(MONTH, 24, C.T)
        THEN 1
        ELSE 0
    END AS Y_CLOSED_24M

FROM BASE B

JOIN COHORTS C
  ON B.LICENSE_DT <= C.T
 AND (
        B.CLOSE_DT IS NULL
        OR B.CLOSE_DT > C.T
     );

SELECT * FROM V_COHORT;

SELECT
    COHORT_YEAR,
    COUNT(*) AS N,
    SUM(Y_CLOSED_24M) AS CLOSED_N,
    ROUND(AVG(Y_CLOSED_24M) * 100, 2) AS CLOSED_RATE_PCT
FROM V_COHORT
GROUP BY COHORT_YEAR
ORDER BY COHORT_YEAR;


SELECT COUNT(*) AS INVALID_CNT
FROM V_COHORT
WHERE CLOSE_DATE IS NOT NULL
  AND TRY_TO_DATE(CLOSE_DATE) <= COHORT_DATE;

  SELECT COUNT(*) AS INVALID_CNT
FROM V_COHORT
WHERE TRY_TO_DATE(LICENSE_DATE) > COHORT_DATE;




SELECT
    SHOP_ID,
    SHOP_NAME,
    COHORT_YEAR,
    COHORT_DATE,
    LICENSE_DATE,
    CLOSE_DATE,
    Y_CLOSED_24M
FROM V_COHORT
WHERE Y_CLOSED_24M = 1
LIMIT 30;

SELECT COUNT(*) AS INVALID_Y_CNT
FROM V_COHORT
WHERE Y_CLOSED_24M = 1
  AND (
        CLOSE_DATE IS NULL
        OR TRY_TO_DATE(CLOSE_DATE) <= COHORT_DATE
        OR TRY_TO_DATE(CLOSE_DATE) > DATEADD(MONTH, 24, COHORT_DATE)
      );

SELECT
    COUNT(*) AS ROW_CNT,
    COUNT(DISTINCT SHOP_ID) AS UNIQUE_SHOPS
FROM V_COHORT;

SELECT DISTINCT
    COHORT_YEAR,
    COHORT_DATE
FROM V_COHORT
ORDER BY COHORT_YEAR;


SELECT COUNT(*) AS LABEL_MISMATCH_CNT
FROM V_COHORT
WHERE Y_CLOSED_24M <>
    CASE
        WHEN CLOSE_DATE IS NOT NULL
         AND TRY_TO_DATE(CLOSE_DATE) > COHORT_DATE
         AND TRY_TO_DATE(CLOSE_DATE) <= DATEADD(MONTH, 24, COHORT_DATE)
        THEN 1
        ELSE 0
    END;


CREATE OR REPLACE VIEW V_COHORT AS

WITH COHORTS AS (

    SELECT 2014 AS COHORT_YEAR, TO_DATE('2014-01-01') AS COHORT_DATE, 'PRE' AS PERIOD
    UNION ALL
    SELECT 2015, TO_DATE('2015-01-01'), 'PRE'
    UNION ALL
    SELECT 2016, TO_DATE('2016-01-01'), 'PRE'
    UNION ALL
    SELECT 2017, TO_DATE('2017-01-01'), 'PRE'
    UNION ALL
    SELECT 2018, TO_DATE('2018-01-01'), 'PRE'

    UNION ALL

    SELECT 2021, TO_DATE('2021-01-01'), 'POST'
    UNION ALL
    SELECT 2022, TO_DATE('2022-01-01'), 'POST'
    UNION ALL
    SELECT 2023, TO_DATE('2023-01-01'), 'POST'
),

BASE AS (

    SELECT
        F.*,
        TRY_TO_DATE(F.LICENSE_DATE) AS LICENSE_DT,
        TRY_TO_DATE(F.CLOSE_DATE) AS CLOSE_DT
    FROM FOOD_ALL F
)

SELECT
    B.*,

    C.COHORT_YEAR,
    C.COHORT_DATE,
    C.PERIOD,

    CASE
        WHEN B.CLOSE_DT > C.COHORT_DATE
         AND B.CLOSE_DT <= DATEADD(MONTH, 24, C.COHORT_DATE)
        THEN 1
        ELSE 0
    END AS Y_CLOSED_24M

FROM BASE B

JOIN COHORTS C
    ON B.LICENSE_DT <= C.COHORT_DATE

   AND (
        B.CLOSE_DT IS NULL
        OR B.CLOSE_DT > C.COHORT_DATE
   );


SELECT
    PERIOD,
    COHORT_YEAR,
    COUNT(*) AS N,
    SUM(Y_CLOSED_24M) AS CLOSED_N,
    ROUND(AVG(Y_CLOSED_24M) * 100, 2) AS CLOSED_RATE_PCT
FROM V_COHORT
GROUP BY PERIOD, COHORT_YEAR
ORDER BY COHORT_YEAR;


