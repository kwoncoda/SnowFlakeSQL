CREATE OR REPLACE VIEW V_GEO AS

WITH GEO_CALC AS (

    SELECT
        C.*,

        ST_DISTANCE(
            ST_MAKEPOINT(C.LON, C.LAT),
            ST_MAKEPOINT(127.42718, 36.32752)
        ) AS DIST_ANCHOR,

        ST_DISTANCE(
            ST_MAKEPOINT(C.LON, C.LAT),
            ST_MAKEPOINT(127.42750, 36.32870)
        ) AS DIST_CENTER,

        MOD(
            DEGREES(
                ATAN2(
                    C.LON - 127.42750,
                    C.LAT - 36.32870
                )
            ) + 360,
            360
        ) AS BEARING

    FROM V_COHORT C

    WHERE C.LAT IS NOT NULL
      AND C.LON IS NOT NULL
),

ANGLE_CALC AS (

    SELECT
        G.*,

        LEAST(
            ABS(G.BEARING - 195.2),
            360 - ABS(G.BEARING - 195.2)
        ) AS ANGLE_DIFF

    FROM GEO_CALC G
)

SELECT
    A.*,

    CASE
        WHEN A.ANGLE_DIFF <= 60
            THEN 'ANCHOR'

        WHEN A.ANGLE_DIFF >= 120
            THEN 'OPPOSITE'

        ELSE 'SIDE'
    END AS SECTOR,

    CASE
        WHEN A.DIST_CENTER <= 150
            THEN '0-150m'

        WHEN A.DIST_CENTER <= 300
            THEN '150-300m'

        WHEN A.DIST_CENTER <= 450
            THEN '300-450m'

        WHEN A.DIST_CENTER <= 600
            THEN '450-600m'

        WHEN A.DIST_CENTER <= 800
            THEN '600-800m'

        ELSE '800m+'
    END AS CENTER_BAND

FROM ANGLE_CALC A;


SELECT
    SECTOR,
    COUNT(*) AS N,
    SUM(Y_CLOSED_24M) AS CLOSED_N,
    ROUND(
        AVG(Y_CLOSED_24M) * 100,
        1
    ) AS CLOSED_RATE_PCT

FROM V_GEO

WHERE PERIOD = 'POST'
  AND DIST_CENTER <= 300
  AND SECTOR IN ('ANCHOR', 'OPPOSITE')

GROUP BY SECTOR

ORDER BY SECTOR;


SELECT
    CENTER_BAND,
    SECTOR,
    COUNT(*) AS N,
    ROUND(
        AVG(Y_CLOSED_24M) * 100,
        2
    ) AS CLOSED_RATE_PCT

FROM V_GEO

WHERE PERIOD = 'POST'
